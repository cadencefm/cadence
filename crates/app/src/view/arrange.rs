//! Semantic Arrange deck view (Placements, Evaluated Overview, Evaluated Lane Roll).
use crate::{App, ArrangeView, EventInspectionView, LANE_KEYS, SECTION_KEYS};
use cadence_core::arrangement_view::{MAX_VISIBLE_NOTES, MAX_VISIBLE_STEPS};
use cadence_core::material::{Id, PhaseMode};
use cadence_core::mixer::ChannelRef;
use cadence_core::music::note_name;
use cadence_core::runtime::AudioSnapshot;

#[derive(Clone, Debug)]
pub struct ArrangeDeckView {
    pub mode: ArrangeView,
    pub zoom: f32,
    pub song_bars: usize,
    pub page_start_step: usize,
    pub page_steps: usize,
    pub cursor_step: u32,
    pub selected_lane: Option<Id>,
    pub playhead_step: Option<f64>,
    pub solo_audition: bool,
    pub playing: bool,
    pub focused: bool,
    pub jam_active: bool,
    pub playing_loop: Option<(u32, u32)>,
    pub loop_region: Option<(u32, u32)>,
    pub staging_active: bool,
    pub staged_boundary_step: Option<u64>,
    pub sections: Vec<SectionBand>,
    pub pending_edit_bars: Vec<u64>,
    pub lanes: Vec<ArrangeLaneRow>,
    pub evaluated: Option<ArrangeEvaluatedView>,
}

#[derive(Clone, Debug)]
pub struct SectionBand {
    pub id: Id,
    pub name: String,
    pub start_step: u32,
    pub length_steps: u32,
    pub key_char: Option<char>,
    pub active: bool,
    pub queued: bool,
    pub staged: bool,
}

#[derive(Clone, Debug)]
pub struct ArrangeLaneRow {
    pub id: Id,
    pub index: usize,
    pub name: String,
    pub key_char: Option<char>,
    pub selected: bool,
    pub muted: bool,
    pub solo: bool,
    pub staged_mute: Option<bool>,
    pub staged_solo: Option<bool>,
    pub placements: Vec<ArrangePlacementBlock>,
    pub override_info: Option<ArrangeOverrideRow>,
    pub pending: Vec<ArrangeMark>,
    pub staged: Vec<ArrangeMark>,
}

#[derive(Clone, Debug)]
pub struct ArrangePlacementBlock {
    pub id: Id,
    pub part_id: Id,
    pub part_name: String,
    pub start_step: u32,
    pub length_steps: u32,
    pub phase_restart: bool,
    pub has_exceptions: bool,
    pub selected: bool,
}

#[derive(Clone, Debug)]
pub struct ArrangeOverrideRow {
    pub part_id: Id,
    pub part_name: String,
    pub from_step: u64,
    pub end_step: u64,
}

#[derive(Clone, Debug)]
pub struct ArrangeMark {
    pub step: u64,
    pub label: String,
    pub is_release: bool,
}

#[derive(Clone, Debug)]
pub struct ArrangeEvaluatedView {
    pub notes: Vec<ArrangeEvalNote>,
    pub pitch_range: (u8, u8),
    pub root_pc: u8,
    pub scale_pcs: [bool; 12],
    pub provenance: Option<EventInspectionView>,
}

#[derive(Clone, Debug)]
pub struct ArrangeEvalNote {
    pub step: u32,
    /// Fractional sub-step onset inside `step` (`0.0 <= offset < 1.0`).
    pub offset: f32,
    pub gate: f32,
    pub midi: u8,
    pub note_name: String,
    pub velocity: f32,
    pub lane_id: Id,
    pub lane_index: usize,
    pub local_exception: bool,
    /// True when this note is generated by an active live lane override rather than
    /// the underlying static arrangement placement.
    pub live_override: bool,
    pub selected: bool,
    pub channel_muted: bool,
}

impl App {
    pub(super) fn build_arrange_view(
        &self,
        focused: bool,
        snapshot: &AudioSnapshot,
    ) -> ArrangeDeckView {
        let project = self.project();
        let song_bars = project.bars.max(1);
        let playhead_step = self.song_position_smooth(snapshot);
        // Base viewport is `song_bars.min(16)` bars at zoom=1.0, scaled cleanly via
        // `arrange_visible_bars()` (1 bar ..= song horizon / MAX_VISIBLE_STEPS).
        let visible_bars = self.arrange_visible_bars();
        let observed_step = self.observed_transport_step(snapshot);
        let page = self.arrange_view_page(observed_step, visible_bars);
        let page_steps = (visible_bars * 16)
            .min(song_bars * 16)
            .clamp(16, MAX_VISIBLE_STEPS);
        let max_start = (song_bars * 16).saturating_sub(page_steps);
        let page_start_step = page.start.min(max_start);

        let heard_step = self.song_step_heard() as u32;
        let queued_section_start: Option<u64> =
            self.live.pending.iter().find_map(|p| match p.change {
                cadence_core::live::Change::Timeline { segment } => Some(segment.song),
                _ => None,
            });
        let bank_lanes = self.play_bank_lanes();
        let staged_section = self.staged_section();
        let sections: Vec<SectionBand> = project
            .sections
            .iter()
            .enumerate()
            .map(|(i, s)| {
                let start = s.start_step;
                let len = s.length_steps.max(16);
                SectionBand {
                    id: s.id,
                    name: s.name.clone(),
                    start_step: start,
                    length_steps: len,
                    key_char: SECTION_KEYS.get(i).copied(),
                    active: (start..start + len).contains(&heard_step),
                    queued: queued_section_start == Some(u64::from(start)),
                    staged: staged_section == Some(s.id),
                }
            })
            .collect();

        let override_end = self
            .live
            .heard_segment()
            .region
            .map_or((song_bars * 16) as u64, |(start, len)| start + len);

        let lanes: Vec<ArrangeLaneRow> = project
            .lanes
            .iter()
            .enumerate()
            .map(|(index, lane)| {
                let key_char = bank_lanes
                    .iter()
                    .position(|&id| id == lane.id)
                    .and_then(|pos| LANE_KEYS.get(pos).copied());
                let placements = lane
                    .placements
                    .iter()
                    .map(|p| ArrangePlacementBlock {
                        id: p.id,
                        part_id: p.part,
                        part_name: self
                            .part(p.part)
                            .map_or_else(|| "?".into(), |part| part.name.clone()),
                        start_step: p.start_step,
                        length_steps: p.length_steps,
                        phase_restart: p.phase == PhaseMode::Restart,
                        has_exceptions: !p.exceptions.is_empty(),
                        selected: Some(p.id) == self.selected_placement,
                    })
                    .collect();
                let override_info = self.override_from(lane.id).and_then(|from| {
                    let state = self.live.lane_state(lane.id)?;
                    Some(ArrangeOverrideRow {
                        part_id: state.part.part,
                        part_name: self
                            .part(state.part.part)
                            .map_or_else(|| "?".into(), |part| part.name.clone()),
                        from_step: from,
                        end_step: override_end,
                    })
                });
                let pending = self
                    .pending_on_lane(lane.id)
                    .into_iter()
                    .map(|(step, part)| ArrangeMark {
                        step,
                        label: part.map_or_else(
                            || "■ rel".into(),
                            |id| format!("◆ {}", self.part(id).map_or("?", |p| p.name.as_str())),
                        ),
                        is_release: part.is_none(),
                    })
                    .collect();
                let staged = self
                    .staged_on_lane(lane.id)
                    .into_iter()
                    .map(|(step, part)| ArrangeMark {
                        step,
                        label: part.map_or_else(
                            || "□ rel".into(),
                            |id| format!("◇ {}", self.part(id).map_or("?", |p| p.name.as_str())),
                        ),
                        is_release: part.is_none(),
                    })
                    .collect();
                ArrangeLaneRow {
                    id: lane.id,
                    index,
                    name: lane.name.clone(),
                    key_char,
                    selected: Some(lane.id) == self.selected_lane,
                    muted: self.flags().lane_muted(lane.id),
                    solo: self.flags().lane_solo(lane.id),
                    staged_mute: self.staged_lane_mute(lane.id),
                    staged_solo: self.staged_lane_solo(lane.id),
                    placements,
                    override_info,
                    pending,
                    staged,
                }
            })
            .collect();

        let evaluated = if self.arrange_ui.view != ArrangeView::Placements {
            let lane_filter = (self.arrange_ui.view == ArrangeView::Roll)
                .then_some(self.selected_lane)
                .flatten();
            let selected_event = self.selected_arrangement_event().map(|n| n.key);
            let mut root_pc = project.root_midi % 12;
            let mut scale_pcs = [false; 12];
            for &interval in &project.scale {
                let pc =
                    (i16::from(project.root_midi) + i16::from(interval)).rem_euclid(12) as usize;
                scale_pcs[pc] = true;
            }
            root_pc %= 12;

            let mut notes = Vec::new();
            let mut min_midi = 127u8;
            let mut max_midi = 0u8;
            let mut marked_selected = false;
            if let Ok(proj) =
                self.arrangement_projection(page_start_step as u32, page_steps, lane_filter)
            {
                for n in proj.notes {
                    let lane_index = project
                        .lanes
                        .iter()
                        .position(|l| l.id == n.lane)
                        .unwrap_or(0);
                    min_midi = min_midi.min(n.midi);
                    max_midi = max_midi.max(n.midi);
                    let is_selected = !marked_selected && Some(n.key) == selected_event;
                    if is_selected {
                        marked_selected = true;
                    }
                    notes.push(ArrangeEvalNote {
                        step: n.key.song_step,
                        offset: n.offset,
                        gate: n.gate,
                        midi: n.midi,
                        note_name: note_name(n.midi),
                        velocity: n.velocity,
                        lane_id: n.lane,
                        lane_index,
                        local_exception: n.local_exception,
                        live_override: false,
                        selected: is_selected,
                        channel_muted: n.channel_muted,
                    });
                }
            }
            // Project active live lane overrides into the visible window so Overview and
            // Lane Roll display both the underlying arrangement ghost and the live notes.
            let vis_start = page_start_step as u64;
            let vis_end = (page_start_step + page_steps).min(song_bars * 16) as u64;
            let mut eval_buf = Vec::with_capacity(4);
            for lane_row in &lanes {
                if lane_filter.is_some_and(|id| id != lane_row.id)
                    || !self.flags().lane_enabled(lane_row.id)
                {
                    continue;
                }
                let Some(ov) = &lane_row.override_info else {
                    continue;
                };
                let Some(state) = self.live.lane_state(lane_row.id) else {
                    continue;
                };
                let Some(part) = project.part(ov.part_id) else {
                    continue;
                };
                let Some(inst) = project.instrument(part.instrument) else {
                    continue;
                };
                let ch_muted = self
                    .flags()
                    .channel_muted(ChannelRef::Channel(inst.channel));
                let ov_start = ov.from_step.max(vis_start);
                let ov_end = ov.end_step.min(vis_end);
                for song_step in ov_start..ov_end {
                    let pattern_time = match state.part.phase {
                        PhaseMode::Song => song_step as i64 + i64::from(state.part.offset_steps),
                        PhaseMode::Restart => {
                            (song_step.saturating_sub(ov.from_step)) as i64
                                + i64::from(state.part.offset_steps)
                        }
                    };
                    eval_buf.clear();
                    if cadence_core::evaluate::evaluate_notes_into(
                        project,
                        part.pattern,
                        pattern_time,
                        &mut eval_buf,
                    )
                    .is_err()
                    {
                        continue;
                    }
                    for ev in eval_buf.drain(..) {
                        if !ev.step.active {
                            continue;
                        }
                        if notes.len() >= MAX_VISIBLE_NOTES {
                            break;
                        }
                        let offset = ev.offset.clamp(0.0, 0.9999);
                        let main_midi = project.pitch_midi(
                            ev.step.degree,
                            ev.step.accidental,
                            i32::from(part.transpose),
                        );
                        let main_vel = (ev.step.velocity * part.velocity_scale).clamp(0.0, 1.0);
                        min_midi = min_midi.min(main_midi);
                        max_midi = max_midi.max(main_midi);
                        notes.push(ArrangeEvalNote {
                            step: song_step as u32,
                            offset,
                            gate: ev.step.gate,
                            midi: main_midi,
                            note_name: note_name(main_midi),
                            velocity: main_vel,
                            lane_id: lane_row.id,
                            lane_index: lane_row.index,
                            local_exception: false,
                            live_override: true,
                            selected: false,
                            channel_muted: ch_muted,
                        });
                        for tone in &ev.step.chord {
                            if notes.len() >= MAX_VISIBLE_NOTES {
                                break;
                            }
                            let midi = project.pitch_midi(
                                tone.degree,
                                tone.accidental,
                                i32::from(part.transpose),
                            );
                            let velocity = (tone.velocity * part.velocity_scale).clamp(0.0, 1.0);
                            min_midi = min_midi.min(midi);
                            max_midi = max_midi.max(midi);
                            notes.push(ArrangeEvalNote {
                                step: song_step as u32,
                                offset,
                                gate: tone.gate,
                                midi,
                                note_name: note_name(midi),
                                velocity,
                                lane_id: lane_row.id,
                                lane_index: lane_row.index,
                                local_exception: false,
                                live_override: true,
                                selected: false,
                                channel_muted: ch_muted,
                            });
                        }
                    }
                }
            }
            let pitch_range = if min_midi <= max_midi {
                (
                    min_midi.saturating_sub(2),
                    max_midi.saturating_add(2).min(127),
                )
            } else {
                let center = self.arrange_ui.pitch_anchor.unwrap_or(project.root_midi);
                (
                    center.saturating_sub(12),
                    center.saturating_add(12).min(127),
                )
            };
            let provenance = self
                .is_arrangement_inspection()
                .then(|| self.arrangement_inspection())
                .flatten();
            Some(ArrangeEvaluatedView {
                notes,
                pitch_range,
                root_pc,
                scale_pcs,
                provenance,
            })
        } else {
            None
        };

        ArrangeDeckView {
            mode: self.arrange_ui.view,
            zoom: self.arrange_effective_zoom(),
            song_bars,
            page_start_step,
            page_steps,
            cursor_step: self.arrange_ui.step,
            selected_lane: self.selected_lane,
            playhead_step,
            solo_audition: self.is_solo_auditioning(),
            playing: snapshot.playing,
            focused,
            jam_active: self.is_jam(),
            playing_loop: self.playing_loop(),
            loop_region: self.loop_region(),
            staging_active: self.staging().is_some(),
            staged_boundary_step: self.staged_boundary_step(),
            sections,
            pending_edit_bars: self.pending_edit_bars(),
            lanes,
            evaluated,
        }
    }
}

#[cfg(test)]
mod tests {
    use crate::{Action, App, ArrangeView};
    use cadence_core::material::{Pattern, PatternKind, Project};
    use cadence_core::runtime::AudioSnapshot;

    #[test]
    fn zoomed_out_overview_and_roll_project_all_notes_and_sub_step_offsets() {
        let mut project = Project::demo();
        project.bars = 64;
        let bell_ch_id = project.max_id() + 1;
        let bell_inst_id = bell_ch_id + 1;
        let bell_pat_id = bell_ch_id + 2;
        let bell_part_id = bell_ch_id + 3;
        let bell_place_id = bell_ch_id + 4;
        let bell_lane_id = bell_ch_id + 5;
        project
            .mixer
            .channels
            .push(cadence_core::mixer::Channel::new(
                bell_ch_id,
                cadence_core::mixer::ChannelKind::Audio,
                "Bell",
            ));
        project
            .instruments
            .push(cadence_core::material::InstrumentInstance {
                id: bell_inst_id,
                name: "Bell".into(),
                rack: cadence_core::rack::RackPatch::default_synth(),
                channel: bell_ch_id,
            });
        project.patterns.push(Pattern {
            id: bell_pat_id,
            name: "Bell Mini".into(),
            kind: PatternKind::Mini {
                code: "[c5 e5 g5] a5 ~ [d5 f5]".into(),
                steps: 4,
            },
        });
        project.parts.push(cadence_core::material::Part::new(
            bell_part_id,
            "Bell",
            bell_pat_id,
            bell_inst_id,
        ));
        project.lanes.push(cadence_core::material::Lane {
            id: bell_lane_id,
            name: "Bell".into(),
            parts: Vec::new(),
            placements: vec![cadence_core::material::Placement {
                id: bell_place_id,
                part: bell_part_id,
                start_step: 0,
                length_steps: 64 * 16,
                phase: cadence_core::material::PhaseMode::Song,
                offset_steps: 0,
                exceptions: Vec::new(),
            }],
        });
        let mut app = App::new(project, "zoom-overview-test.json".into()).expect("create App");
        let snap = AudioSnapshot::default();

        for (mode, zoom) in [
            (ArrangeView::Overview, 0.25_f32),
            (ArrangeView::Overview, 0.5_f32),
            (ArrangeView::Roll, 0.25_f32),
            (ArrangeView::Roll, 0.5_f32),
        ] {
            app.arrange_ui.view = mode;
            app.arrange_ui.zoom = zoom;
            let view = app.build_arrange_view(true, &snap);
            let eval = view.evaluated.expect("evaluated view");
            assert!(
                !eval.notes.is_empty(),
                "mode={mode:?} zoom={zoom} must project non-empty notes across wide window"
            );
            if zoom == 0.25 {
                assert_eq!(view.page_steps, 1024, "64-bar full-song overview");
            }
            if mode == ArrangeView::Overview {
                assert!(
                    eval.notes.iter().any(|n| n.offset > 0.01),
                    "Bell Mini sub-step offsets must be preserved at zoom={zoom}"
                );
            }
        }
    }

    #[test]
    fn live_override_notes_appear_in_overview_and_roll() {
        let mut project = Project::demo();
        let new_pat_id = 900;
        project.patterns.push(Pattern {
            id: new_pat_id,
            name: "Live Mini".into(),
            kind: PatternKind::Mini {
                code: "[c5 e5 g5] a5".into(),
                steps: 2,
            },
        });
        let inst_id = project.instruments[0].id;
        let part_id = 901;
        project.parts.push(cadence_core::material::Part::new(
            part_id, "LivePart", new_pat_id, inst_id,
        ));
        let lane_id = project.lanes[0].id;
        project.lanes[0]
            .parts
            .push(cadence_core::material::LanePart::new(part_id));

        let mut app = App::new(project, "live_override_test.json".into()).unwrap();
        app.observe_transport(0, 1, true, false);
        app.apply(Action::Launch {
            lane: lane_id,
            part: cadence_core::material::LanePart::new(part_id),
            at: Some(cadence_core::material::Boundary::Now),
        })
        .unwrap();
        app.observe_transport(4, 5, true, false);
        app.arrange_ui.view = ArrangeView::Roll;
        let snap = AudioSnapshot {
            playing: true,
            absolute_step: 4,
            ..AudioSnapshot::default()
        };
        let view = app.build_arrange_view(true, &snap);
        let eval = view.evaluated.expect("evaluated roll");
        let live_notes: Vec<_> = eval.notes.iter().filter(|n| n.live_override).collect();
        assert!(
            !live_notes.is_empty(),
            "expected live override notes in roll"
        );
        assert!(
            live_notes.iter().any(|n| n.offset > 0.2),
            "expected fractional sub-step offsets on live override mini notes"
        );
    }
}
